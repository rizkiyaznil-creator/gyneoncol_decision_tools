/** Slug id stabil dari judul + kanker (untuk key & anchor). */
export function trialId(t) {
  return (t.cancer + '-' + t.title)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

/** URL pencarian PubMed untuk sebuah trial. */
export function trialPubmedUrl(t, cancerName) {
  const term = t.q || `${t.title} ${cancerName || ''}`.trim();
  return 'https://pubmed.ncbi.nlm.nih.gov/?term=' + encodeURIComponent(term);
}
